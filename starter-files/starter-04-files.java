public class Decisiones {
    public static void main(String[] args) {
        int edad = 15;

        // Pregunta: ¿tiene entre 12 y 17 años?
        if (edad >= 12 && edad <= 17) {
            System.out.println("¡Bienvenido al curso!");
        } else {
            System.out.println("Este curso es para estudiantes de secundaria.");
        }
    }
}
