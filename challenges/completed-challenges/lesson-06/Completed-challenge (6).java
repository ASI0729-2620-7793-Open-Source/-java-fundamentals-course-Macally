public class Reto6 {
    public static double areaRectangulo(double ancho, double alto) {
        return ancho * alto;
    }

    public static void main(String[] args) {
        System.out.println("Área: " + areaRectangulo(4, 3)); // 12
        System.out.println("Área: " + areaRectangulo(5, 2)); // 10
    }
}